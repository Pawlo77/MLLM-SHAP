"""Tests for the AI watermark stripper.

@see [[scripts/strip_watermarks.py]]
"""

from collections.abc import Callable
from pathlib import Path
from types import ModuleType

import pytest

ROBOT = "\U0001f916"


@pytest.fixture(scope="module")
def strip(script: Callable[[str], ModuleType]) -> ModuleType:
    """Load scripts/strip_watermarks.py."""
    return script("strip_watermarks")


@pytest.mark.parametrize(
    "line",
    [
        "Co-Authored-By: Claude Fable 5.1 <noreply@anthropic.com>",
        "co-authored-by: Copilot <copilot@github.com>",
        "Co-authored-by: Cursor <cursoragent@cursor.com>",
        "Assisted-by: Codex",
        "Signed-off-by: ChatGPT <bot@openai.com>",
        f"{ROBOT} Generated with [Claude Code](https://claude.com/claude-code)",
        "Generated with Claude Code",
        "# Generated by Claude",
        "// written by an AI assistant",
        "<!-- Made with Gemini -->",
        "/* This file was generated by GPT-4 */",
        '    "# Created by Claude Code\\n",',
        "* Drafted using the help of Claude",
    ],
)
def test_watermark_lines(strip: ModuleType, line: str) -> None:
    assert strip.is_watermark(line)


@pytest.mark.parametrize(
    "line",
    [
        "Co-Authored-By: Jane Doe <jane@example.org>",
        "Commits carry no `Co-Authored-By: Claude` trailer (rule `git-commits`).",
        "Notebooks are generated with Jupyter.",
        "Claude reviews its own work before a PR (skill `review`).",
        "Copilot's review threads are answered by the agent.",
        "# Generated from .cursor/rules/tests.mdc by scripts/sync_rules.py",
        "model: claude-sonnet-4-5",
        "The generator is Qwen2.5-3B-Instruct; the judge is the same model.",
    ],
)
def test_ordinary_lines(strip: ModuleType, line: str) -> None:
    assert not strip.is_watermark(line)


def test_strip_text_commit_message(strip: ModuleType) -> None:
    text = (
        "feat: add x\n\nBody line.\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n"
    )
    new, removed = strip.strip_text(text)
    assert new == "feat: add x\n\nBody line.\n"
    assert removed == [(5, "Co-Authored-By: Claude <noreply@anthropic.com>")]
    assert strip.strip_text(new) == (new, [])


def test_cli_rewrites_and_check_reports(
    strip: ModuleType, tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    body = tmp_path / "body.md"
    body.write_text(
        f"## Summary\n\nWhy.\n\n{ROBOT} Generated with [Claude Code](https://x)\n",
        encoding="utf-8",
    )
    binary = tmp_path / "blob.bin"
    binary.write_bytes(b"\0Generated with Claude")
    assert strip.main(["--check", str(body), str(binary)]) == 1
    assert "body.md:5:" in capsys.readouterr().out
    assert body.read_text(encoding="utf-8").endswith("Claude Code](https://x)\n")
    assert strip.main([str(body), str(binary)]) == 0
    assert body.read_text(encoding="utf-8") == "## Summary\n\nWhy.\n"
    assert binary.read_bytes() == b"\0Generated with Claude"
    assert strip.main([str(body)]) == 0


def test_own_files_are_skipped(strip: ModuleType) -> None:
    here = Path(__file__).resolve()
    assert strip.strip_file(here, check=True) == []
    assert (
        strip.strip_file(strip.ROOT / "scripts" / "strip_watermarks.py", check=True)
        == []
    )
