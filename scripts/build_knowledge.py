IMPORT_FROM = re.compile(
    r"^\s*from\s+(\.+[\w.]*|mllm_shap[\w.]*)\s+import\s", re.MULTILINE
)
IMPORT_PLAIN = re.compile(r"^\s*import\s+(mllm_shap[\w.]*)", re.MULTILINE)


def graph(root: Path) -> tuple[set[str], set[tuple[str, str, str]]]:
    """Return (nodes, edges) of the offline code and note graph."""
    vault = Vault.load(root)
    py = [
        path
        for folder in ("src", "tests", "scripts", "examples", "docs")
        for path in sorted((root / folder).rglob("*.py"))
        if "_build" not in path.parts
    ]
    md = vault.notes + vault.plans + vault.memory
    nodes = {path.relative_to(root).as_posix() for path in py + md}
    edges: set[tuple[str, str, str]] = set()

    def add(source: Path, target: Path | None, kind: str) -> None:
        if target is None:
            return
        a, b = source.relative_to(root).as_posix(), target.relative_to(root).as_posix()
        if a != b and b in nodes:
            edges.add((a, b, kind))

    for path in py:
        text = path.read_text(encoding="utf-8")
        for match in IMPORT_FROM.finditer(text):
            spec = match.group(1)
            level = len(spec) - len(spec.lstrip("."))
            if level:
                add(path, relative_module(path, spec[level:] or None, level), "imports")
            else:
                add(path, module_file(root, spec), "imports")
        for match in IMPORT_PLAIN.finditer(text):
            add(path, module_file(root, match.group(1)), "imports")
        for match in LINK.finditer(comments_and_docstrings(path)):
            add(path, vault.resolve(match.group(1)), "comment-link")
    for path in md:
        text = path.read_text(encoding="utf-8")
        for match in LINK.finditer(strip_code(text)):
            add(path, vault.resolve(match.group(1)), "md-link")
        for item in frontmatter(text).get("related-code") or []:
            match = LINK.search(str(item))
            target = (match.group(1) if match else str(item)).strip()
            add(
                path,
                root / target if (root / target).exists() else None,
                "related-code",
            )
    return nodes, edges


def print_graph(root: Path, argv: list[str]) -> int:
    """Print the graph summary, code map or one node's neighbours."""
    nodes, edges = graph(root)
    if "--neighbors" in argv:
        position = argv.index("--neighbors")
        if position + 1 >= len(argv):
            print("usage: --neighbors <path or note name>")
            return 2
        wanted = argv[position + 1]
        vault = Vault.load(root)
        resolved = vault.resolve(wanted)
        target = resolved.relative_to(root).as_posix() if resolved else wanted
        if target not in nodes:
            print(f"graph: unknown node {wanted!r}")
            return 1
        print(target)
        for direction, pick, other in (
            ("outgoing", lambda e: e[0] == target, lambda e: e[1]),
            ("incoming", lambda e: e[1] == target, lambda e: e[0]),
        ):
            grouped: dict[str, list[str]] = defaultdict(list)
            for edge in edges:
                if pick(edge):
                    grouped[edge[2]].append(other(edge))
            for kind in sorted(grouped):
                print(f"  {direction} {kind}:")
                for item in sorted(grouped[kind]):
                    print(f"    {item}")
        return 0
    if "--codemap" in argv:
        notes = related_code_index(root)
        current = ""
        for path in sorted((root / PACKAGE).rglob("*.py")):
            rel = path.relative_to(root / PACKAGE)
            package = rel.parts[0] if len(rel.parts) > 1 else "(root)"
            if package != current:
                current = package
                print(f"{package}/")
            doc = ast.get_docstring(parse(path)) or ""
            owners = ",".join(sorted(notes.get(path.relative_to(root).as_posix(), [])))
            print(f"  {rel.as_posix():<40} {first_line(doc)[:60]}  [{owners}]")
        return 0
    degree: dict[str, int] = defaultdict(int)
    kinds: dict[str, int] = defaultdict(int)
    for source, target, kind in edges:
        degree[source] += 1
        degree[target] += 1
        kinds[kind] += 1
    isolated = sorted(node for node in nodes if degree[node] == 0)
    summary = ", ".join(f"{kind} {count}" for kind, count in sorted(kinds.items()))
    print(f"graph: {len(nodes)} nodes, {len(edges)} edges ({summary})")
    if isolated:
        print(f"graph: {len(isolated)} isolated node(s):")
        for node in isolated:
            print(f"  {node}")
