JIT_INDEX = "00-index.tsv"
"""Per-layer index the plugin's hooks read instead of the Markdown entries."""

JIT_KEYWORD_BLACKLIST = re.compile(
    r"^(extension|detection|count|output|input|name|branch|issue|documents|files|file)$"
)
"""Keywords the plugin never indexes (its default ``JIT_CONTEXT_KEYWORD_BLACKLIST``)."""

MACRO_ANCHOR = r"(^|[;&|\n] *)"
MACRO_WRAP = (
    r"(([a-z_][a-z0-9_]*=[^[:space:];&|]*|rtk|command|[e]nv|sudo|nohup|nice|time)"
    r"[[:space:]]+)*"
)
MACRO_OPT = (
    r"(-[^[:space:];&|]*[[:space:]]+([^-;&|[:space:]][^[:space:];&|]*[[:space:]]+)?)*"
)
MACRO_END = r"($|[[:space:];&|])"
"""Pieces of the plugin's ``~@invocation`` expansion (``scripts/common.sh``)."""


def expand_invocation(match: str) -> str:
    """Expand ``~@invocation <words>`` to the awk ERE the plugin's indexer writes.

    Any other ``match`` value is returned unchanged.
    """
    body = match.removeprefix("~")
    if not body.startswith("@invocation "):
        return match
    words = body.removeprefix("@invocation ").lower().split()
    pieces = [
        "".join(c if re.fullmatch(r"[a-z0-9_/]", c) else f"[{c}]" for c in word)
        for word in words
    ]
    joined = f"[[:space:]]+{MACRO_OPT}".join(pieces)
    return f"~{MACRO_ANCHOR}{MACRO_WRAP}{joined}{MACRO_END}"


def index_keywords(line: str) -> list[str]:
    """Normalise a ``keywords:`` line the way the plugin's indexer does."""
    out = []
    for raw in line.split(","):
        keyword = " ".join(re.sub(r"[^a-z0-9 -]", " ", raw.lower()).split())
        if keyword and not JIT_KEYWORD_BLACKLIST.match(keyword):
            out.append(keyword)
    return out


def build_jit_indexes(entries: dict[Path, str]) -> dict[Path, str]:
    r"""Return the ``00-index.tsv`` of every layer that holds generated entries.

    Rows follow the plugin's indexer: ``paths`` ``<match>\t<file>``; ``vocabulary``
    ``<keyword>\t<file>\t`` (empty generic-word verdict: every keyword counts as
    specific); ``tools`` ``<tool>\t<match>\t<file>\t<mode>\t<require>\t<forbid>\t
    <requires>`` with invocation macros expanded.
    """
    rows: dict[Path, list[str]] = defaultdict(list)
    for path in sorted(entries):
        meta = frontmatter(entries[path])
        name = path.name
        dimension = path.parent.parent.name
        if dimension == "paths":
            rows[path.parent].append(f"{meta['match']}\t{name}")
        elif dimension == "vocabulary":
            rows[path.parent] += [
                f"{keyword}\t{name}\t"
                for keyword in index_keywords(str(meta["keywords"]))
            ]
        else:
            fields = [
                str(meta["tool"]),
                expand_invocation(str(meta["match"])),
                name,
                str(meta.get("mode") or "remind"),
                str(meta.get("require") or ""),
                str(meta.get("forbid") or ""),
                str(meta.get("requires") or ""),
            ]
            rows[path.parent].append("\t".join(fields))
    return {layer / JIT_INDEX: "\n".join(lines) + "\n" for layer, lines in rows.items()}


