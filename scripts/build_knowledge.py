def load_extra() -> Any:
    """Return the project's ``scripts/knowledge_extra.py``, ``None`` without one."""
    if "knowledge_extra" in sys.modules:
        return sys.modules["knowledge_extra"]
    path = SCRIPTS / "knowledge_extra.py"
    if not path.is_file():
        return None
    spec = importlib.util.spec_from_file_location("knowledge_extra", path)
    if spec is None or spec.loader is None:
        return None
    module = importlib.util.module_from_spec(spec)
    sys.modules["knowledge_extra"] = module
    spec.loader.exec_module(module)
    return module


