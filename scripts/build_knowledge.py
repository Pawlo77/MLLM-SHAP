def release_sections(text: str) -> list[tuple[str, str, dict[str, int]]]:
    """Return (version, date, counts per subsection) from release notes RST."""
    lines = text.splitlines()
    out: list[tuple[str, str, dict[str, int]]] = []
    current: dict[str, int] | None = None
    section = ""
    for index, line in enumerate(lines):
        underline = lines[index + 1] if index + 1 < len(lines) else ""
        if underline and set(underline) == {"-"} and len(underline) >= len(line) > 0:
            match = re.match(r"(\S+)(?: \(([^)]*)\))?$", line.strip())
            version, released = (
                (match.group(1), match.group(2) or "")
                if match
                else (
                    line.strip(),
                    "",
                )
            )
            current = {}
            out.append((version, released, current))
            section = ""
            continue
        if (
            current is not None
            and underline
            and set(underline) == {"~"}
            and len(underline) >= len(line) > 0
        ):
            section = line.strip()
            continue
        if current is not None and section and line.startswith("- "):
            current[section] = current.get(section, 0) + 1
    return out


