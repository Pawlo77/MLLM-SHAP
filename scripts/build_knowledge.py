"""Build the generated vault notes that describe the source package.

Usage:
    python scripts/build_knowledge.py [--check]

Writes ``knowledge/generated/*.md`` from the code with ``ast`` and ``pyproject.toml``:
Modules, Public API, Entry points and Dependencies (``generators`` in
``[tool.agent-kit.knowledge]``). ``--check`` writes nothing and exits 1 when a note is
stale. Project builders live in ``scripts/knowledge_extra.py`` (``BUILDERS``, and
optionally ``main`` to take over the command line).
"""

import ast
import importlib.util
import re
import sys
import tomllib
from collections import defaultdict
from collections.abc import Callable
from datetime import date
from pathlib import Path
from typing import Any

SCRIPTS = Path(__file__).resolve().parent
ROOT = SCRIPTS.parent
sys.path.insert(0, str(SCRIPTS))

from check_vault import LINK, Vault, frontmatter  # noqa: E402
from kit_config import load as load_config  # noqa: E402

DEFAULTS: dict[str, Any] = {
    "package": "",
    "out": "knowledge/generated",
    "generators": ["modules", "public-api", "entry-points", "dependencies"],
    "domain": "generated",
    "parent": "",
    "updated": False,
    "module-note-type": "module",
}
"""Settings used when ``[tool.agent-kit.knowledge]`` leaves a key out."""

TODAY = "@DATE@"
"""Placeholder of the ``updated`` date; :func:`finalize` keeps it stable."""


def settings(root: Path = ROOT) -> dict[str, Any]:
    """Return ``[tool.agent-kit.knowledge]`` over :data:`DEFAULTS`."""
    table = load_config(root).get("knowledge", {})
    return {**DEFAULTS, **(table if isinstance(table, dict) else {})}


def package_dir(root: Path = ROOT) -> Path:
    """Return the source package folder relative to ``root`` (``src/<name>``)."""
    named = settings(root)["package"]
    if named:
        return Path(named)
    found = sorted((root / "src").glob("*/__init__.py"))
    return found[0].parent.relative_to(root) if found else Path("src")


def cell(text: object) -> str:
    """Return ``text`` safe for a Markdown table cell."""
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def header(title: str, source: str, root: Path | None = None) -> str:
    """Return the frontmatter and do-not-edit banner of a generated note."""
    cfg = settings(root or ROOT)
    extra = f'parent: "{cfg["parent"]}"\n' if cfg["parent"] else ""
    extra += f"updated: {TODAY}\n" if cfg["updated"] else ""
    return (
        "---\n"
        f'title: "{title}"\n'
        "type: generated\n"
        f"domain: {cfg['domain']}\n"
        "generated: true\n"
        "tags: [generated]\n"
        f"{extra}"
        "---\n"
        f"# {title}\n\n"
        f"> [!note] Generated by `scripts/build_knowledge.py` from {source}. "
        "Do not edit by hand; run `make knowledge`.\n\n"
    )


def finalize(path: Path, text: str) -> str:
    """Fill the ``updated`` date: kept from the file while the rest is unchanged."""
    if TODAY not in text:
        return text
    stamp = date.today().isoformat()
    if path.is_file():
        old = path.read_text(encoding="utf-8")
        match = re.search(r"(?m)^updated: (\S+)$", old)
        if match and old.replace(match.group(0), f"updated: {TODAY}", 1) == text:
            stamp = match.group(1)
    return text.replace(TODAY, stamp)


# ---------------------------------------------------------------- ast helpers


def parse(path: Path) -> ast.Module:
    """Parse a Python file."""
    return ast.parse(path.read_text(encoding="utf-8"))


def first_line(doc: str | None) -> str:
    """Return the first non-empty line of a docstring."""
    for line in (doc or "").splitlines():
        if line.strip():
            return line.strip()
    return ""


def module_file(root: Path, dotted: str) -> Path | None:
    """Return the file of an absolute module path below the package's parent."""
    base = root / package_dir(root).parent / Path(*dotted.split("."))
    for candidate in (base.with_suffix(".py"), base / "__init__.py"):
        if candidate.is_file():
            return candidate
    return None


def relative_module(path: Path, module: str | None, level: int) -> Path | None:
    """Return the file a relative import in ``path`` refers to."""
    base = path.parent
    for _ in range(level - 1):
        base = base.parent
    target = base / Path(*module.split(".")) if module else base
    for candidate in (target.with_suffix(".py"), target / "__init__.py"):
        if candidate.is_file():
            return candidate
    return None


def find_definition(
    root: Path, path: Path, name: str, depth: int = 0
) -> tuple[Path, ast.AST] | None:
    """Follow imports from ``path`` to the class or function called ``name``."""
    if depth > 8:
        return None
    tree = parse(path)
    for node in tree.body:
        if (
            isinstance(node, ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef)
            and node.name == name
        ):
            return path, node
    for node in tree.body:
        if not isinstance(node, ast.ImportFrom):
            continue
        for alias in node.names:
            if (alias.asname or alias.name) != name:
                continue
            if node.level:
                target = relative_module(path, node.module, node.level)
            else:
                target = module_file(root, node.module or "")
            if target is not None:
                return find_definition(root, target, alias.name, depth + 1)
    return None


def definition_index(root: Path) -> dict[str, list[tuple[Path, ast.AST]]]:
    """Return every top-level class and function in the package by name."""
    index: dict[str, list[tuple[Path, ast.AST]]] = defaultdict(list)
    for path in sorted((root / package_dir(root)).rglob("*.py")):
        for node in parse(path).body:
            if isinstance(node, ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
                index[node.name].append((path, node))
    return index


def docstring_of(node: ast.AST) -> str | None:
    """Return the docstring of a class or function node."""
    if isinstance(node, ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
        return ast.get_docstring(node)
    return None


def module_tags(doc: str) -> tuple[str, str]:
    """Return the ``@domain`` value and ``@see`` target of a module docstring."""
    domain = re.search(r"@domain\s+(\S+)", doc)
    see = re.search(r"@see\s+\[\[([^\]|#]+)", doc)
    return (domain.group(1) if domain else "", see.group(1) if see else "")


# ---------------------------------------------------------------- notes data


def notes_of_type(root: Path, kind: str) -> list[tuple[Path, dict[str, Any]]]:
    """Return (path, frontmatter) for the vault notes of one type."""
    out: list[tuple[Path, dict[str, Any]]] = []
    for path in sorted(Vault.load(root).notes):
        meta = frontmatter(path.read_text(encoding="utf-8"))
        if meta.get("type") == kind:
            out.append((path, meta))
    return out


def related_code_index(root: Path) -> dict[str, list[str]]:
    """Return code path -> names of the module notes listing it in ``related-code``."""
    index: dict[str, list[str]] = defaultdict(list)
    for path, meta in notes_of_type(root, settings(root)["module-note-type"]):
        for item in meta.get("related-code") or []:
            match = LINK.search(str(item))
            target = (match.group(1) if match else str(item)).strip()
            index[target].append(path.stem)
    return index


# ---------------------------------------------------------------- generators


def build_modules(root: Path) -> str:
    """Return the Modules note."""
    package = package_dir(root)
    notes = related_code_index(root)
    entries = []
    for path in sorted((root / package).rglob("*.py")):
        rel = path.relative_to(root).as_posix()
        text = path.read_text(encoding="utf-8")
        doc = ast.get_docstring(ast.parse(text)) or ""
        entries.append((rel, doc, *module_tags(doc), text.count("\n")))
    tagged = any(domain or see for _, _, domain, see, _ in entries)
    columns = ["Module", "Summary"] + (["Domain", "See"] if tagged else []) + ["Lines"]
    columns += ["Architecture note"] if notes else []
    rows = []
    orphans = []
    for rel, doc, domain, see, lines in entries:
        owners = notes.get(rel, [])
        if not owners:
            orphans.append(rel)
        cells = [f"[[{rel}]]", cell(first_line(doc))]
        cells += [cell(domain), f"[[{see}]]" if see else ""] if tagged else []
        cells.append(str(lines))
        if notes:
            cells.append(", ".join(f"[[{owner}]]" for owner in sorted(owners)))
        rows.append("| " + " | ".join(cells) + " |")
    body = header("Modules", f"the module docstrings in `{package.as_posix()}`", root)
    body += f"| {' | '.join(columns)} |\n|{'---|' * len(columns)}\n"
    body += "\n".join(rows) + "\n"
    if notes:
        body += "\n## Modules no architecture note lists\n\n"
        body += (
            "\n".join(f"- [[{item}]]" for item in orphans) if orphans else "None."
        ) + "\n"
    return body


def public_names(init: Path) -> list[str]:
    """Return the names in the ``__all__`` of a package ``__init__``."""
    names: list[str] = []
    for node in parse(init).body:
        if (
            isinstance(node, ast.Assign)
            and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id == "__all__"
            and isinstance(node.value, ast.List | ast.Tuple)
        ):
            names = [
                str(item.value)
                for item in node.value.elts
                if isinstance(item, ast.Constant)
            ]
    return names


def build_public_api(root: Path) -> str:
    """Return the Public API note."""
    package = package_dir(root)
    init = root / package / "__init__.py"
    index = definition_index(root)
    rows = []
    for name in public_names(init):
        if name == "__version__":
            rows.append("| `__version__` | | Installed package version string. |")
            continue
        found = find_definition(root, init, name)
        if found is None and index.get(name):
            found = min(index[name], key=lambda item: len(item[0].parts))
        source = found[0].relative_to(root).as_posix() if found else ""
        summary = first_line(docstring_of(found[1])) if found else ""
        link = f"[[{source}]]" if source else ""
        rows.append(f"| `{name}` | {link} | {cell(summary)} |")
    body = header("Public API", f"`{package.name}.__all__`", root)
    body += "| Name | Defined in | Summary |\n|---|---|---|\n" + "\n".join(rows) + "\n"
    return body


def project_table(root: Path) -> dict[str, Any]:
    """Return the ``[project]`` table of pyproject.toml."""
    path = root / "pyproject.toml"
    return tomllib.loads(path.read_text(encoding="utf-8")).get("project", {})


def build_entry_points(root: Path) -> str:
    """Return the Entry points note ("" when the project declares none)."""
    project = project_table(root)
    groups = {"console_scripts": project.get("scripts", {})}
    groups.update(project.get("entry-points", {}))
    rows = []
    for group, items in sorted(groups.items()):
        for name, target in sorted(items.items()):
            module, _, attr = str(target).partition(":")
            path = module_file(root, module)
            found = find_definition(root, path, attr) if path and attr else None
            source = found[0].relative_to(root).as_posix() if found else ""
            summary = first_line(docstring_of(found[1])) if found else ""
            link = f"[[{source}]]" if source else ""
            rows.append(
                f"| {cell(group)} | `{name}` | `{cell(target)}` | {link} | "
                f"{cell(summary)} |"
            )
    if not rows:
        return ""
    body = header("Entry points", "`pyproject.toml`", root)
    body += (
        "| Group | Name | Target | Defined in | Summary |\n|---|---|---|---|---|\n"
        + "\n".join(rows)
        + "\n"
    )
    return body


def build_dependencies(root: Path) -> str:
    """Return the Dependencies note: Python version, requirements, extras, groups."""
    data = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
    project = data.get("project", {})
    rows = [("Python", "", cell(project.get("requires-python", "")))]
    rows += [("Runtime", "", cell(item)) for item in project.get("dependencies", [])]
    for extra, items in sorted(project.get("optional-dependencies", {}).items()):
        rows += [("Extra", extra, cell(item)) for item in items]
    for group, items in sorted(data.get("dependency-groups", {}).items()):
        rows += [
            ("Group", group, cell(item)) for item in items if isinstance(item, str)
        ]
    body = header("Dependencies", "`pyproject.toml`", root)
    body += "| Scope | Extra or group | Requirement |\n|---|---|---|\n"
    body += "\n".join(f"| {scope} | {name} | {req} |" for scope, name, req in rows)
    return body + "\n"


GENERATORS: dict[str, tuple[str, Callable[[Path], str]]] = {
    "modules": ("Modules", build_modules),
    "public-api": ("Public API", build_public_api),
    "entry-points": ("Entry points", build_entry_points),
    "dependencies": ("Dependencies", build_dependencies),
}
"""Generator key -> (note name, builder)."""


def load_extra() -> Any:
    """Return the project's ``scripts/knowledge_extra.py``, ``None`` without one."""
    if "knowledge_extra" in sys.modules:
        return sys.modules["knowledge_extra"]
    path = SCRIPTS / "knowledge_extra.py"
    if not path.is_file():
        return None
    spec = importlib.util.spec_from_file_location("knowledge_extra", path)
    if spec is None or spec.loader is None:
        return None
    module = importlib.util.module_from_spec(spec)
    sys.modules["knowledge_extra"] = module
    spec.loader.exec_module(module)
    return module


def build_all(root: Path = ROOT) -> dict[Path, str]:
    """Return every generated note path with its content."""
    cfg = settings(root)
    out = root / cfg["out"]
    builders = {
        GENERATORS[key][0]: GENERATORS[key][1]
        for key in cfg["generators"]
        if key in GENERATORS
    }
    extra = load_extra()
    builders.update(getattr(extra, "BUILDERS", {}))
    notes = {out / f"{name}.md": builder(root) for name, builder in builders.items()}
    return {path: finalize(path, text) for path, text in notes.items() if text}


def write_changed(outputs: dict[Path, str]) -> int:
    """Write the outputs whose content changed; return how many were written."""
    changed = 0
    for path, content in outputs.items():
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        changed += 1
    return changed


def main(argv: list[str], root: Path = ROOT) -> int:
    """Build or check the generated notes; return the exit status."""
    extra = load_extra()
    if hasattr(extra, "main"):
        return int(extra.main(argv, root))
    if not (load_config(root).get("knowledge") or (root / "knowledge").is_dir()):
        print("knowledge: no knowledge folder; nothing to build")
        return 0
    notes = build_all(root)
    if "--check" in argv:
        stale = [
            path.relative_to(root).as_posix()
            for path, text in notes.items()
            if not path.is_file() or path.read_text(encoding="utf-8") != text
        ]
        for item in stale:
            print(f"{item}: stale; run `make knowledge`")
        if not stale:
            print(f"knowledge: {len(notes)} generated notes up to date")
        return 1 if stale else 0
    changed = write_changed(notes)
    print(f"knowledge: {changed} of {len(notes)} generated notes rewritten")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
