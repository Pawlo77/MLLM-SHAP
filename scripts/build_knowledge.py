def model_fields(tree: ast.Module, class_name: str) -> list[tuple[str, str, str, str]]:
    """Return (name, type, default, docstring) of a pydantic model's fields."""
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == class_name:
            fields = []
            body = node.body
            for index, statement in enumerate(body):
                if not (
                    isinstance(statement, ast.AnnAssign)
                    and isinstance(statement.target, ast.Name)
                ):
                    continue
                name = statement.target.id
                if name == "model_config":
                    continue
                default = ast.unparse(statement.value) if statement.value else ""
                doc = ""
                if index + 1 < len(body):
                    following = body[index + 1]
                    if isinstance(following, ast.Expr) and isinstance(
                        following.value, ast.Constant
                    ):
                        doc = str(following.value.value)
                fields.append((
                    name,
                    ast.unparse(statement.annotation),
                    default,
                    first_line(doc),
                ))
            return fields
    return []


